-- events.id stays an independent autoincrement key with no foreign links.
-- events.event_id is the application's event key; registrations reference it.
ALTER TABLE public.events
    ADD COLUMN IF NOT EXISTS time text,
    ADD COLUMN IF NOT EXISTS recurrence text,
    ADD COLUMN IF NOT EXISTS "maxParticipants" integer NOT NULL DEFAULT 50,
    ADD COLUMN IF NOT EXISTS event_id bigint,
    ADD COLUMN IF NOT EXISTS created_by uuid DEFAULT auth.uid() REFERENCES auth.users (id) ON DELETE SET NULL;

UPDATE public.events SET event_id = id WHERE event_id IS NULL;

ALTER TABLE public.events
    ALTER COLUMN event_id SET NOT NULL,
    ALTER COLUMN recurrence DROP NOT NULL,
    ALTER COLUMN created_at SET DEFAULT now();

DO $$
DECLARE
    target_column text;
    sequence_name text;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'events_event_id_key'
          AND conrelid = 'public.events'::regclass
    ) THEN
        ALTER TABLE public.events
            ADD CONSTRAINT events_event_id_key UNIQUE (event_id);
    END IF;

    FOREACH target_column IN ARRAY ARRAY['id', 'event_id'] LOOP
        IF NOT EXISTS (
            SELECT 1
            FROM information_schema.columns AS columns
            WHERE columns.table_schema = 'public'
              AND columns.table_name = 'events'
              AND columns.column_name = target_column
              AND (columns.is_identity = 'YES' OR columns.column_default IS NOT NULL)
        ) THEN
            EXECUTE format(
                'ALTER TABLE public.events ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',
                target_column
            );
        END IF;

        sequence_name := pg_get_serial_sequence('public.events', target_column);
        IF sequence_name IS NOT NULL THEN
            EXECUTE format(
                'SELECT setval(%L, coalesce((SELECT max(%I) FROM public.events), 1), EXISTS (SELECT 1 FROM public.events))',
                sequence_name, target_column
            );
        END IF;
    END LOOP;

    ALTER TABLE public.events DROP CONSTRAINT IF EXISTS events_recurrence_check;
    ALTER TABLE public.events
        ADD CONSTRAINT events_recurrence_check
        CHECK (recurrence IS NULL OR recurrence IN ('daily', 'weekly', 'monthly', 'yearly'));
END
$$;

