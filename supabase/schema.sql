CREATE OR REPLACE FUNCTION public.get_hub_question()
RETURNS TABLE (id bigint, question text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT questions.id, questions.question
    FROM public.hub_questions AS questions
    WHERE (questions.available_from IS NULL OR questions.available_from <= (now() AT TIME ZONE 'Europe/Moscow')::date)
      AND (questions.available_to IS NULL OR questions.available_to >= (now() AT TIME ZONE 'Europe/Moscow')::date)
    ORDER BY random()
    LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.check_hub_answer(p_id bigint, p_answer text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = extensions, pg_temp
AS $$
    SELECT coalesce((
        SELECT questions.answer_hash = extensions.crypt(lower(trim(coalesce(p_answer, ''))), questions.answer_hash)
        FROM public.hub_questions AS questions
        WHERE questions.id = p_id
          AND (questions.available_from IS NULL OR questions.available_from <= (now() AT TIME ZONE 'Europe/Moscow')::date)
          AND (questions.available_to IS NULL OR questions.available_to >= (now() AT TIME ZONE 'Europe/Moscow')::date)
    ), false);
$$;

CREATE OR REPLACE FUNCTION public.save_hub_question(
    p_id bigint,
    p_question text,
    p_answer text,
    p_description text,
    p_from date,
    p_to date
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = extensions, pg_temp
AS $$
DECLARE
    saved_id bigint;
    has_answer boolean := length(trim(coalesce(p_answer, ''))) > 0;
BEGIN
    IF NOT public.is_buhlo_admin() THEN
        RAISE EXCEPTION 'Недостаточно прав';
    END IF;

    IF p_id IS NULL THEN
        IF NOT has_answer THEN
            RAISE EXCEPTION 'Для нового вопроса нужен правильный ответ';
        END IF;
        INSERT INTO public.hub_questions (question, answer_hash, description, available_from, available_to)
        VALUES (
            trim(p_question),
            extensions.crypt(lower(trim(p_answer)), extensions.gen_salt('bf')),
            coalesce(p_description, ''),
            p_from,
            p_to
        )
        RETURNING id INTO saved_id;
    ELSE
        UPDATE public.hub_questions AS questions
        SET question = trim(p_question),
            answer_hash = CASE WHEN has_answer
                THEN extensions.crypt(lower(trim(p_answer)), extensions.gen_salt('bf'))
                ELSE questions.answer_hash END,
            description = coalesce(p_description, ''),
            available_from = p_from,
            available_to = p_to
        WHERE questions.id = p_id
        RETURNING questions.id INTO saved_id;

        IF saved_id IS NULL THEN
            RAISE EXCEPTION 'Вопрос не найден';
        END IF;
    END IF;

    RETURN saved_id;
END;
$$;

