CREATE OR REPLACE FUNCTION public.submit_event_registration(
    p_event_id bigint,
    p_registration_key uuid,
    p_name text,
    p_contact text DEFAULT 'не указан',
    p_notes text DEFAULT ''
)
RETURNS TABLE (registration_id bigint, event_id bigint, name text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    event_limit integer;
    current_count bigint;
    account_name text;
    saved_registration public.event_registrations%ROWTYPE;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Для записи необходимо войти в аккаунт' USING ERRCODE = '42501';
    END IF;

    SELECT nullif(btrim(profiles.username), '')
    INTO account_name
    FROM public.user_profiles AS profiles
    WHERE profiles.id = auth.uid();

    IF account_name IS NULL THEN
        RAISE EXCEPTION 'В профиле аккаунта не указано имя';
    END IF;

    IF p_registration_key IS NULL
       OR length(account_name) > 120
       OR length(coalesce(p_contact, '')) > 200
       OR length(coalesce(p_notes, '')) > 2000 THEN
        RAISE EXCEPTION 'Некорректные данные регистрации';
    END IF;

    SELECT coalesce(events."maxParticipants", 50)
    INTO event_limit
    FROM public.events AS events
    WHERE events.event_id = p_event_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Событие не найдено';
    END IF;

    SELECT count(*)
    INTO current_count
    FROM public.event_registrations AS registrations
    WHERE registrations.event_id = p_event_id;

    SELECT *
    INTO saved_registration
    FROM public.event_registrations AS registrations
    WHERE registrations.event_id = p_event_id
      AND registrations.registration_key = p_registration_key;

    IF FOUND THEN
        RETURN QUERY SELECT saved_registration.id, saved_registration.event_id, saved_registration.name;
        RETURN;
    END IF;

    IF current_count >= event_limit THEN
        RAISE EXCEPTION 'Мест на событие больше нет';
    END IF;

    INSERT INTO public.event_registrations (event_id, registration_key, name, contact, notes)
    VALUES (
        p_event_id,
        p_registration_key,
        account_name,
        coalesce(nullif(trim(p_contact), ''), 'не указан'),
        coalesce(trim(p_notes), '')
    )
    RETURNING * INTO saved_registration;

    RETURN QUERY SELECT saved_registration.id, saved_registration.event_id, saved_registration.name;
END;
$$;

CREATE OR REPLACE FUNCTION public.replace_events(p_events jsonb)
RETURNS void
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    IF NOT public.is_buhlo_admin() OR p_events IS NULL OR jsonb_typeof(p_events) <> 'array' THEN
        RAISE EXCEPTION 'Недостаточно прав или неверный список событий';
    END IF;

    INSERT INTO public.events (
        event_id, title, date, time, location, description, recurrence, "maxParticipants"
    )
    SELECT
        item.event_id, item.title, item.date, nullif(item.time, ''),
        coalesce(item.location, ''), item.description, item.recurrence,
        coalesce(item."maxParticipants", 50)
    FROM jsonb_to_recordset(p_events) AS item(
        event_id bigint,
        title text,
        date date,
        time text,
        location text,
        description text,
        recurrence text,
        "maxParticipants" integer
    )
    ON CONFLICT (event_id) DO UPDATE SET
        title = EXCLUDED.title,
        date = EXCLUDED.date,
        time = EXCLUDED.time,
        location = EXCLUDED.location,
        description = EXCLUDED.description,
        recurrence = EXCLUDED.recurrence,
        "maxParticipants" = EXCLUDED."maxParticipants";

    DELETE FROM public.events AS events
    WHERE NOT EXISTS (
        SELECT 1
        FROM jsonb_to_recordset(p_events) AS item(event_id bigint)
        WHERE item.event_id = events.event_id
    );

    INSERT INTO public.event_registrations (
        event_id, registration_key, name, contact, notes, registered_at
    )
    SELECT
        item.event_id,
        gen_random_uuid(),
        trim(imported.person->>'name'),
        coalesce(nullif(trim(imported.person->>'contact'), ''), 'не указан'),
        coalesce(imported.person->>'notes', ''),
        coalesce(nullif(imported.person->>'registeredAt', '')::timestamptz, now())
    FROM jsonb_to_recordset(p_events) AS item(event_id bigint, participants jsonb)
    CROSS JOIN LATERAL jsonb_array_elements(
        CASE
            WHEN jsonb_typeof(item.participants) = 'array' THEN item.participants
            ELSE '[]'::jsonb
        END
    ) AS imported(person)
    WHERE jsonb_typeof(imported.person) = 'object'
      AND length(trim(coalesce(imported.person->>'name', ''))) BETWEEN 1 AND 120
      AND NOT EXISTS (
          SELECT 1 FROM public.event_registrations AS existing
          WHERE existing.event_id = item.event_id
      );

    IF pg_get_serial_sequence('public.events', 'event_id') IS NOT NULL THEN
        PERFORM setval(
            pg_get_serial_sequence('public.events', 'event_id'),
            coalesce((SELECT max(event_id) FROM public.events), 1),
            EXISTS (SELECT 1 FROM public.events)
        );
    END IF;
END;
$$;

