CREATE TABLE IF NOT EXISTS public.holidays (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date text NOT NULL CHECK (
        date ~ '^(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])$'
